"""Merge the browser check of official pages (data/pib_verification.jsonl) into the labels.

Inputs: data/claims.jsonl, data/bindings.jsonl (left untouched), data/pib_verification.jsonl.
Outputs: data/bindings_verified.jsonl and data/summary_verified.md. Every number in the
summary is computed here. A binding counts as verified only when its page was opened
(fetched == "yes"); unverified bindings keep their old label and are kept out of the
verified counts. Usage: python -I scripts/merge_verification.py"""
import json
import os
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from summarize import LABELS, geo_level, load, pct, table  # noqa: E402

CORRECTABLE = {"label", "ambiguity_type", "as_of_date", "reason", "official_figure"}


def merge(binds, ver):
    out = []
    for b in binds:
        r = dict(b)
        v = ver.get(b["id"])
        if b["label"] == "unbindable":
            r["verification"] = "not applicable (no official figure)"
        elif v is None or v["fetched"] != "yes":
            r["verification"] = "unverified"
            r["verified"] = False
        else:
            corr = v.get("corrected") or {}
            unknown = set(corr) - CORRECTABLE
            if unknown:
                raise SystemExit(f"{b['id']}: unknown correction fields {sorted(unknown)}: fix data/pib_verification.jsonl")
            if corr:
                r["original"] = {k: b.get(k) for k in corr}
                r.update(corr)
                if r["label"] != "bound-ambiguous":
                    r.pop("ambiguity_type", None)
            r["verified"] = True
            r["verification"] = "page opened in browser and figure checked"
            r["verification_note"] = v["note"]
            r["verification_quotes"] = v["page_quotes"]
            if r.get("evidence_access") == "search_extract":
                r["evidence_access"] = "browser_verified"
                if r.get("confidence") == 2:
                    r["confidence"] = 3
        out.append(r)
    return out


def main():
    claims = load("claims.jsonl")
    binds = load("bindings.jsonl")
    ver = {v["id"]: v for v in load("pib_verification.jsonl")}
    merged = merge(binds, ver)
    with open(os.path.join(ROOT, "data", "bindings_verified.jsonl"), "w", encoding="utf-8") as f:
        for r in merged:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    old = {b["id"]: b for b in binds}
    bind = {b["id"]: b for b in merged}
    n = len(claims)
    lab = Counter(bind[c["id"]]["label"] for c in claims)
    old_lab = Counter(old[c["id"]]["label"] for c in claims)
    bound = [c for c in claims if bind[c["id"]]["label"] != "unbindable"]
    verified = [c for c in bound if bind[c["id"]].get("verified")]
    unverified = [c for c in bound if not bind[c["id"]].get("verified")]
    changed_label = [c for c in bound if bind[c["id"]]["label"] != old[c["id"]]["label"]]
    corrected = [c for c in bound if "original" in bind[c["id"]]]
    vlab = Counter(bind[c["id"]]["label"] for c in verified)

    strict_bound = lab["bound+match"] + lab["bound+mismatch"]
    strict_ids = [c["id"] for c in claims if bind[c["id"]]["label"] in ("bound+match", "bound+mismatch")]
    lenient = sum(1 for i in strict_ids if bind[i]["lenient_match"])
    v_strict = vlab["bound+match"] + vlab["bound+mismatch"]
    access = Counter(bind[c["id"]].get("evidence_access") for c in bound)
    amb = Counter(bind[c["id"]].get("ambiguity_type") for c in bound if bind[c["id"]]["label"] == "bound-ambiguous")

    L = ["# Saboot: data-phase summary (official pages verified)", "",
         "Generated by `scripts/merge_verification.py` from `data/claims.jsonl`, `data/bindings.jsonl` and "
         "`data/pib_verification.jsonl`. Labels are in `data/bindings_verified.jsonl`; the original "
         "`data/bindings.jsonl` and `data/summary.md` are unchanged. Do not edit numbers by hand; re-run the script.", "",
         "**Status: labels under the fixed rules; every official page re-opened in a browser.** "
         "See `data/labelling-rules.md` §5 and §7.", "",
         "## Verification", "",
         f"- Bound or ambiguous claims: {len(bound)}; official page opened and figure checked: **{len(verified)}**; "
         f"unverified: {len(unverified)}" + (f" ({', '.join(c['id'] for c in unverified)})" if unverified else "") + ".",
         f"- Bindings with a correction (label, date or reason): {len(corrected)} "
         f"({', '.join(c['id'] for c in corrected) or 'none'}).",
         f"- Label changes: {len(changed_label)}"
         + "".join(f"; {c['id']} {old[c['id']]['label']} -> {bind[c['id']]['label']}" for c in changed_label) + ".",
         "- Page texts as read are stored in `data/raw/pib_browser/` (one file per evidence page).", "",
         "## Labels (strict rule)", "", "| Label | Before verification | After verification | Of which page-verified |",
         "|---|---:|---:|---:|"]
    L += [f"| {x} | {old_lab[x]} | {lab[x]} | {vlab[x] if x != 'unbindable' else '-'} |" for x in LABELS]
    L += [f"| total | {n} | {n} | {len(verified)} |", ""]
    L += ["## Headline rates (after verification)", "",
          f"- Coverage (match + mismatch + ambiguous) / all: {pct(len(bound), n)}",
          f"- Strict coverage (match + mismatch) / all: {pct(strict_bound, n)}",
          f"- Match rate, strict rule: {pct(lab['bound+match'], strict_bound)}",
          f"- Match rate, lenient rule (±5%, ±1 pp for percentages): {pct(lenient, strict_bound)}",
          f"- Match rate, strict rule, page-verified bindings only: {pct(vlab['bound+match'], v_strict)}",
          f"- Coverage, India-level claims: {pct(sum(1 for c in bound if geo_level(c) == 'India'), sum(1 for c in claims if geo_level(c) == 'India'))}",
          f"- Coverage, state-level claims: {pct(sum(1 for c in bound if geo_level(c) == 'State'), sum(1 for c in claims if geo_level(c) == 'State'))}",
          "", "Evidence access for bound/ambiguous claims: " + ", ".join(f"{k} {v}" for k, v in access.most_common())
          + " (browser_verified = PIB page opened in a browser and the figure found on it; fetched = page fetched directly and re-checked in the browser).",
          "", "Ambiguity types: " + ", ".join(f"{k} {v}" for k, v in amb.most_common()) + ".", ""]
    L += ["## Corrections", ""]
    for c in corrected:
        b = bind[c["id"]]
        changes = "; ".join(f"{k}: {b['original'][k]!r} -> {b[k]!r}" for k in b["original"] if k != "reason")
        L += [f"- **{c['id']}** ({c['scheme']}, {c['outlet']}): {changes or 'reason corrected'}. {b['verification_note']}"]
    L += ["", "## Breakdowns (after verification)", ""]
    L += table("By scheme", lambda c: c["scheme"], claims, bind)
    L += table("By outlet", lambda c: c["outlet"], claims, bind)
    L += table("By geography", geo_level, claims, bind)
    mism = sorted((c for c in claims if bind[c["id"]]["label"] == "bound+mismatch"),
                  key=lambda c: -abs(bind[c["id"]]["relative_gap"]))
    L += ["## Strict mismatches (largest gap first)", ""]
    for c in mism:
        b = bind[c["id"]]
        L += [f"- **{c['id']}** ({c['scheme']}, {c['outlet']}, {c['pub_date']}): claimed {c['number_raw']}; official "
              f"{b['official_figure']:,.0f} ({b['as_of_date']}); gap {100 * b['relative_gap']:+.1f}%; "
              f"verified on page: {b.get('verified')}. Official: {b['bound_official_url']}"]
    L += [""]
    with open(os.path.join(ROOT, "data", "summary_verified.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
