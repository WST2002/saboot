"""Write data/summary.md. Every number in it is computed here from
data/claims.jsonl, data/bindings.jsonl, data/articles_log.jsonl and
data/binding_evidence.jsonl. Usage: python -I scripts/summarize.py"""
import json
import math
import os
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LABELS = ["bound+match", "bound+mismatch", "bound-ambiguous", "unbindable"]


def load(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
        return [json.loads(x) for x in f if x.strip()]


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return centre - half, centre + half


def pct(k, n):
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.1f}% (95% CI {100 * lo:.1f}-{100 * hi:.1f}%)" if n else f"{k}/0"


def table(title, key_fn, claims, bind):
    groups = defaultdict(Counter)
    for c in claims:
        groups[key_fn(c)][bind[c["id"]]["label"]] += 1
    rows = [f"### {title}", "", "| " + title.split(" ")[-1].capitalize() + " | " + " | ".join(LABELS) + " | total |",
            "|---|" + "---:|" * (len(LABELS) + 1)]
    for g in sorted(groups, key=lambda g: (-sum(groups[g].values()), g)):
        cnt = groups[g]
        rows.append(f"| {g} | " + " | ".join(str(cnt[label]) for label in LABELS) + f" | {sum(cnt.values())} |")
    return rows + [""]


def geo_level(c):
    return "India" if c["geography"] == "India" else "State"


def main():
    claims = load("claims.jsonl")
    bind = {b["id"]: b for b in load("bindings.jsonl")}
    arts = load("articles_log.jsonl")
    n = len(claims)
    lab = Counter(bind[c["id"]]["label"] for c in claims)

    fetched_ok = [a for a in arts if str(a["fetch_status"]) in ("200", "cached")]
    in_window = [a for a in fetched_ok if "2026-08-01" <= (a.get("pub_date") or "")[:10] <= "2026-11-13"]
    with_claim = {c["url"] for c in claims} | {d["url"] for c in claims for d in c.get("duplicates", [])}
    failed = [a for a in arts if str(a["fetch_status"]) not in ("200", "cached")]
    dup_count = sum(len(c.get("duplicates", [])) for c in claims)

    bound_all = lab["bound+match"] + lab["bound+mismatch"] + lab["bound-ambiguous"]
    strict_bound = lab["bound+match"] + lab["bound+mismatch"]
    bound_ids = [c["id"] for c in claims if bind[c["id"]]["label"] in ("bound+match", "bound+mismatch")]
    lenient_match = sum(1 for i in bound_ids if bind[i]["lenient_match"])
    access = Counter(bind[c["id"]].get("evidence_access") for c in claims if bind[c["id"]]["label"] != "unbindable")
    amb = Counter(bind[c["id"]].get("ambiguity_type") for c in claims if bind[c["id"]]["label"] == "bound-ambiguous")

    L = ["# Saboot: data-phase summary", "",
         "Generated by `scripts/summarize.py` from `data/claims.jsonl`, `data/bindings.jsonl` and "
         "`data/articles_log.jsonl`. Do not edit numbers by hand; re-run the script.", "",
         "**Status: first-pass labels by an AI agent, not yet reviewed by the author.** "
         "See `data/labelling-rules.md` §5 and §7 before using any number below.", "",
         "## Collection", "",
         f"- Articles fetched: {len(arts)} attempted, {len(fetched_ok)} fetched, {len(failed)} failed "
         f"(failures logged in `data/articles_log.jsonl`).",
         f"- Fetched articles dated 1 Aug - 13 Nov 2026: {len(in_window)}; of these, articles contributing at least one "
         f"claim (kept or duplicate): {len(with_claim & {a['url'] for a in in_window})}.",
         f"- Claims kept: **{n}** (India/state level); duplicates removed by the 7-day rule: {dup_count}.",
         f"- Outlets: " + ", ".join(f"{k} {v}" for k, v in Counter(c['outlet'] for c in claims).most_common()) + ".",
         "", "## Labels (strict rule)", "", "| Label | Claims |", "|---|---:|"]
    L += [f"| {label} | {lab[label]} |" for label in LABELS] + [f"| total | {n} |", ""]
    L += ["## Headline rates", "",
          f"- Coverage (any binding: match + mismatch + ambiguous) / all: {pct(bound_all, n)}",
          f"- Strict coverage (match + mismatch) / all: {pct(strict_bound, n)}",
          f"- Match rate, strict rule: {pct(lab['bound+match'], strict_bound)}",
          f"- Match rate, lenient rule (±5%, ±1 pp for percentages): {pct(lenient_match, strict_bound)}",
          f"- Coverage, India-level claims: {pct(sum(1 for c in claims if geo_level(c) == 'India' and bind[c['id']]['label'] != 'unbindable'), sum(1 for c in claims if geo_level(c) == 'India'))}",
          f"- Coverage, state-level claims: {pct(sum(1 for c in claims if geo_level(c) == 'State' and bind[c['id']]['label'] != 'unbindable'), sum(1 for c in claims if geo_level(c) == 'State'))}",
          "", "Evidence access for bound/ambiguous claims: " + ", ".join(f"{k} {v}" for k, v in access.most_common())
          + " (search_extract = PIB page text seen only through a search-engine extract; PIB returned HTTP 403).",
          "", "Ambiguity types: " + ", ".join(f"{k} {v}" for k, v in amb.most_common()) + ".", ""]
    L += ["## Breakdowns", ""]
    L += table("By scheme", lambda c: c["scheme"], claims, bind)
    L += table("By outlet", lambda c: c["outlet"], claims, bind)
    L += table("By geography", geo_level, claims, bind)
    L += table("By speaker", lambda c: c["speaker"].split(" (")[0], claims, bind)

    mism = [c for c in claims if bind[c["id"]]["label"] == "bound+mismatch"]
    mism.sort(key=lambda c: -abs(bind[c["id"]]["relative_gap"]))
    L += ["## Mismatches (all strict mismatches, largest gap first)", "",
          f"Only {len(mism)} claims are strict mismatches, so fewer than five can be listed.", ""]
    for c in mism:
        b = bind[c["id"]]
        L += [f"### {c['id']} · {c['scheme']} · {c['outlet']} · {c['pub_date']}", "",
              f"- Claim: \"{c['claim_text_hi']}\" ({c['english_gloss']})",
              f"- Claimed {c['number_raw']} = {c['number']:,.0f}; official {b['official_figure']:,.0f} "
              f"({b['as_of_date']}); gap {100 * b['relative_gap']:+.1f}%; lenient match: {b['lenient_match']}",
              f"- Why: {b['reason']}",
              f"- Article: {c['url']}", f"- Official: {b['bound_official_url']} ({b['evidence_access']})", ""]
    near = [c for c in claims if bind[c["id"]]["label"] == "bound-ambiguous" and bind[c["id"]]["strict_match"] is False]
    near.sort(key=lambda c: -abs(bind[c["id"]]["relative_gap"]))
    L += ["## Ambiguous claims whose number also differs from the nearest official figure", "",
          "Not mismatches under the rules (different period or definition); listed so the author can judge them.", ""]
    for c in near[:5]:
        b = bind[c["id"]]
        L += [f"- **{c['id']}** ({c['scheme']}, {c['outlet']}, {c['pub_date']}): claimed {c['number_raw']}; "
              f"official {b['official_figure']:,.2f} as of {b['as_of_date']} ({b['ambiguity_type']}). {b['reason']} "
              f"Article: {c['url']} · Official: {b['bound_official_url']}"]
    L += ["", "## Blockers", "",
          "- pib.gov.in answered HTTP 403 to the study's fetcher and to WebFetch on 14 Nov 2026; PIB evidence comes from search extracts and must be confirmed by hand.",
          "- jagran.com and navbharattimes.indiatimes.com (methodology outlets) refuse the agent; replaced by Patrika, Prabhat Khabar, Aaj Tak.",
          "- JJM dashboard figures load by JavaScript; state rows were not readable, so most state JJM claims are unbindable.",
          "- State-wise PM-KISAN instalment figures were not found in any central source; all state PM-KISAN claims are unbindable.",
          "- Parliament answers cited by articles (Lok Sabha 20 Mar 2026, Aug 2026 PM-JAY reply) were not located; sansad.in search is JavaScript-only.", ""]
    with open(os.path.join(ROOT, "data", "summary.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("\n".join(L[:40]))


if __name__ == "__main__":
    main()
